# 2026-11-10 (user): jobs stuck behind ~420 higher-priority l40s_public jobs on torch_pr_61_general (fair-share
# 0.11) -> submit on torch_pr_61_tandon_priority (fair-share 0.32, ~+2,000 priority). Applies to every
# E.submit_* call made by this driver.
ACCOUNT = "torch_pr_61_tandon_priority"
E.ACCOUNT = ACCOUNT

METRICS = E.METRICS
STATE_DIR = os.path.join(METRICS, "opexp45")
STATE = os.path.join(STATE_DIR, "state.json")
STATUS_MD = os.path.join(REPO, "md_guides", "experiments", "opexp45_status.md")
OPEXP_CFG_DIR = os.path.join(REPO, "PatchPerPix", "experiments", "flylight", "setups", "setup01",
                             "configs", "exp", "opexp")

# OP-EXP 4
SRC_EXP, SRC_CKPT, SRC_KEY = "expv2-e1.1-pre-n1000", 20000, "1.1"
FT_ITERS = 6000
WARMUP_FRAC = 0.10
ARMS4 = [("4.1", 5e-5, "5e-5"), ("4.2", 1e-5, "1e-5"), ("4.3", 5e-6, "5e-6")]
# OP-EXP 5 / references
REF_FT, REF_CKPT, REF_FT_KEY = "expv2-e1.3-ft-n1000-completely", 23000, "1.3"
REF_FT_OVERLAYS = E.COMMON + ["expv2_e1_ft.toml", f"expv2_e1_ft_{REF_FT}.toml"]
ARMS5 = [("5.1", 500), ("5.2", 1000), ("5.3", 1500)]
# Single evaluate job over all 7 volumes (no per-volume array in evaluate mode): longer limit.
# 96g (user 2026-11-09): the first 64g runs (22447080/81/86) stalled at the memory cap.
EVAL5_ENV = {"EVAL_MEM": "96g", "EVAL_PARTITION": "cs", "EVAL_TIME": "03:00:00"}

DRY = False


def log(state, msg):
    E.log(state, msg)


def initial_state():
    op4 = {}
    for key, lr, tag in ARMS4:
        exp = f"opexp4-ft-lr{tag}"
        op4[key] = {
            "stage": "seed",
            "ft": {"key": key, "exp": exp, "lr": lr, "status": "new", "jobs": [], "retries": 0,
                   "label": f"finetune completely from 1.1 @ {SRC_CKPT}, peak lr {tag}"},
            "test": {"key": key, "status": "wait", "jobs": [], "retries": 0,
                     "label": f"test completely, best {key} ckpt"},
        }
    op5 = {}
    for key, rm in ARMS5:
        op5[key] = {"key": key, "rm": rm, "exp": f"opexp5-e1.3-rm{rm}", "ckpt": REF_CKPT,
                    "status": "new", "jobs": [], "retries": 0,
                    "label": f"re-evaluate 1.3 @ {REF_CKPT} labels, remove_small_components {rm}"}
    return {"op4": op4, "op5": op5, "events": [], "done": False}


# ----------------------------------------------------------------------------- OP-EXP 4

def start_finetune(state, ft):
    n = SRC_CKPT
    ft["src_ckpt"], ft["start_it"], ft["max_it"] = n, n, n + FT_ITERS
    gen = f"opexp4_ft_{ft['exp']}.toml"
    # written in --dry-run too, so the dry-run submitter can resolve it (deterministic content)
    if True:
        with open(os.path.join(OPEXP_CFG_DIR, gen), "w") as fh:
            fh.write(f"# generated by sbatch/ppp/opexp/opexp45.py: OP-EXP {ft['key']} finetunes "
                     f"{SRC_EXP} @ {n} for {FT_ITERS} its, peak lr {ft['lr']:g}.\n"
                     f"[training]\nmax_iterations = {n + FT_ITERS}\n\n"
                     f"[optimizer.optimizer]\nlr = {ft['lr']!r}\n\n"
                     f"[optimizer.lr_scheduler]\nstart_iter = {n}\n")
    ft["overlays"] = E.COMMON + ["expv2_e1_ft.toml", "opexp4_ft.toml", gen]
    if not DRY:
        dst = os.path.join(METRICS, ft["exp"], "train")
        inner = (f"source /ext3/env.sh; conda activate ppp; python sbatch/ppp/expv2/seed_finetune_ckpt.py "
                 f"--src {E.ckpt_path(SRC_EXP, n)} --dst-dir {dst} --iteration {n} --lr {ft['lr']!r} "
                 f"--warmup-frac {WARMUP_FRAC} --ft-iters {FT_ITERS}")
        out = E.run(["singularity", "exec", "--overlay", "env/ppp.ext3:ro", E.SIF, "/bin/bash", "-c", inner])
        log(state, f"OP-EXP {ft['key']}: " + out.strip().splitlines()[-1])
    E.submit_train(state, ft, E.FT_TIME)


def submit_test(state, ft, te):
    """E.submit_test with an optional --stage: te["resume_stage"] = "label" requeues the label graph -> label
    -> evaluate chain on the existing predictions (no predict); volumes already labelled are skipped
    (label_resume.toml; ppp_job.sh does not require their stripped pred_affs)."""
    stage = te.pop("resume_stage", None)
    te["exp"], te["ckpt"] = ft["exp"], ft["best_ckpt"]
    cmd = ["./sbatch/ppp/ppp_submit_test.sh"] + (["--dry-run"] if DRY else []) + [
        "array", E.PRESET, "--id", ft["exp"], "--split", "test", "--ckpt", str(ft["best_ckpt"]),
        "--base", E.BASE]
    for o in ft["overlays"] + [E.SPARSE_CFG]:
        cmd += ["--config", o]
    cmd += ["--pct", str(E.TEST_PCT), "--account", ACCOUNT] + (["--stage", stage] if stage else [])
    out = E.run(cmd, env=E.EVAL_ENV)
    ids = re.findall(r"(?:array_job|evaluate)=(\d+)", out)
    ev = re.findall(r"evaluate=(\d+)", out)
    if DRY or not ev:
        if stage:
            te["resume_stage"] = stage
        log(state, f"[dry] would submit test {te['key']} (stage {stage or 'all'})")
        return
    te["jobs"], te["eval_job"], te["status"] = ids, ev[-1], "testing"
    log(state, f"OP-EXP {te['key']}: test {ft['exp']} @ {ft['best_ckpt']} (stage {stage or 'all'}, {ACCOUNT}): "
               f"jobs {','.join(ids)} (evaluate {ev[-1]})")


def requeue_tests(state, resume_stage="label"):
    """Cancel each OP-EXP 4 arm's queued test chain and resubmit it (current ACCOUNT) from resume_stage."""
    for key, arm in state["op4"].items():
        te = arm["test"]
        if arm["stage"] != "test" or te["status"] != "testing":
            continue
        if not DRY:
            subprocess.run(["scancel"] + te["jobs"])
        te.setdefault("requeued_jobs", []).extend(te["jobs"])
        te["jobs"], te["status"], te["retries"], te["resume_stage"] = [], "wait", 0, resume_stage
        log(state, f"OP-EXP {key}: cancelled test chain {','.join(te['requeued_jobs'][-5:])} to requeue on "
                   f"{ACCOUNT} from stage {resume_stage}")


def tick_op4(state, arm):
    ft, te = arm["ft"], arm["test"]
    if arm["stage"] == "seed":
        start_finetune(state, ft)
        if ft["status"] == "training":
            arm["stage"] = "train"
    elif arm["stage"] == "train":
        if ft["status"] == "training" and E.advance_training(state, ft, E.FT_TIME):
            E.select_best(state, ft, min_it=ft["start_it"])
            arm["stage"] = "test"
            submit_test(state, ft, te)
        if ft["status"] == "failed":
            arm["stage"] = "failed"
    elif arm["stage"] == "test":
        if te["status"] == "testing":
            E.advance_testing(state, ft, te)
        elif te["status"] == "wait":  # requeued, or submit_test did not go through last tick
            submit_test(state, ft, te)
        if te["status"] == "tested":
            arm["stage"] = "done"
        elif te["status"] == "failed":
            arm["stage"] = "failed"


# ----------------------------------------------------------------------------- OP-EXP 5

def instanced_src():
    return os.path.join(METRICS, REF_FT, "test", "instanced", str(REF_CKPT))


def prepare_eval_dir(a):
    """Copy 1.3's labels into the arm's own exp dir (same instanced/<ckpt>/<params>/<dataset> layout).
    Only plain files (<sample>.hdf labels + .png previews) are copied; the <sample>.zarr dirs are the
    label-graph caches (~950 small files each, ~10 files/s on /scratch) that evaluate does not read.
    No config.toml: 1.3's saved config points `base` at 1.3's dir; run_ppp writes a fresh one."""
    src_root = instanced_src()
    dst_root = os.path.join(METRICS, a["exp"], "test", "instanced", str(REF_CKPT))
    if os.path.isdir(dst_root):
        return dst_root
    for d, subdirs, files in os.walk(src_root):
        subdirs[:] = [s for s in subdirs if not s.endswith(".zarr")]
        out = os.path.join(dst_root, os.path.relpath(d, src_root))
        os.makedirs(out, exist_ok=True)
        for f in files:
            shutil.copy2(os.path.join(d, f), os.path.join(out, f))
    return dst_root


def submit_eval(state, a):
    if not DRY:
        prepare_eval_dir(a)
    cmd = ["./sbatch/ppp/ppp_submit_test.sh"] + (["--dry-run"] if DRY else []) + [
        "evaluate", E.PRESET, "--id", a["exp"], "--split", "test", "--ckpt", str(REF_CKPT),
        "--base", E.BASE]
    for o in REF_FT_OVERLAYS + [E.SPARSE_CFG]:
        cmd += ["--config", o]
    cmd += ["--eval", f"eval_rm{a['rm']}.toml", "--account", E.ACCOUNT]
    out = E.run(cmd, env=EVAL5_ENV)
    ev = [m for m in out.split() if m.startswith("evaluate=")]
    jid = ev[-1].split("=", 1)[1] if ev else None
    if DRY or not jid or not jid.isdigit():
        log(state, f"[dry] would submit evaluate {a['key']} ({a['exp']})")
        return
    a["jobs"].append(jid)
    a["status"] = "evaluating"
    log(state, f"OP-EXP {a['key']}: evaluate {REF_FT} @ {REF_CKPT} labels with remove_small_components "
               f"{a['rm']}: job {jid} exp={a['exp']}")


def tick_op5(state, a):
    if a["status"] == "new":
        submit_eval(state, a)
        return
    if a["status"] != "evaluating":
        return
    jid = a["jobs"][-1]
    st, reason = E.job_states([jid]).get(jid, ("UNKNOWN", ""))
    if st in E.ACTIVE:
        return
    path = E.summary_csv(a["exp"], REF_CKPT)
    if st == "COMPLETED" and path:
        a["scores"], a["summary_csv"], a["status"] = E.read_scores(path), os.path.relpath(path, REPO), "tested"
        s = a["scores"]
        log(state, f"OP-EXP {a['key']}: tested S={s['S']:.4f} avF1={s['avF1']:.4f} C={s['C']:.4f} "
                   f"nPred={s['num_pred']:.1f} (n={s['n']})")
    elif a["retries"] < E.MAX_RETRIES:
        a["retries"] += 1
        log(state, f"OP-EXP {a['key']}: evaluate job {jid} ended {st} {reason}; retrying")
        submit_eval(state, a)
    else:
        a["status"] = "failed"
        log(state, f"OP-EXP {a['key']}: evaluate failed twice ({st})")


# ----------------------------------------------------------------------------- tick

def tick(state):
    for arm in state["op4"].values():
        try:
            tick_op4(state, arm)
        except Exception as e:  # keep the other arms going
            log(state, f"OP-EXP {arm['ft']['key']}: tick error {type(e).__name__}: {str(e)[:300]}")
    for a in state["op5"].values():
        try:
            tick_op5(state, a)
        except Exception as e:
            log(state, f"OP-EXP {a['key']}: tick error {type(e).__name__}: {str(e)[:300]}")
    done4 = all(arm["stage"] in ("done", "failed") for arm in state["op4"].values())
    done5 = all(a["status"] in ("tested", "failed") for a in state["op5"].values())
    if done4 and done5 and not state.get("done"):
        state["done"] = True
        log(state, "OP-EXP 4/5 driver finished")


# ----------------------------------------------------------------------------- status md

def ref_scores():
    p = E.summary_csv(REF_FT, REF_CKPT)
    return (E.read_scores(p), os.path.relpath(p, REPO)) if p else ({}, None)


def score_cells(s):
    if not s:
        return "— | — | — | — | — | — | — | —"
    return (f"**{E.fmt(s['S'])}** | {E.fmt(s['avF1'])} | {E.fmt(s['C'])} | {E.fmt(s['clDiceTP'])} | "
            f"{E.fmt(s['tp'])} | {E.fmt(s['FS'], 2)} | {E.fmt(s['FM'], 2)} | "
            f"{E.fmt(s['num_pred'], 0)} / {E.fmt(s['num_gt'], 1)}")


def fresh_scores(a):
    p = os.path.join(REPO, a["summary_csv"]) if a.get("summary_csv") else None
    return E.read_scores(p) if p and os.path.exists(p) else (a.get("scores") or {})


METRIC_HDR = "S | avF1 | C | clDiceTP | tp | FS | FM | nPred / nGT"


def write_status(state):
    ref, ref_path = ref_scores()
    ref_val = E.val_rows(REF_FT, 20000)
    ref_best = min(ref_val, key=lambda r: (r[1], -r[0])) if ref_val else None
    L = ["# experiment_v2 OP-EXP 4 / 5 status (auto-generated by `sbatch/ppp/opexp/opexp45.py`)", "",
         f"Last update: {E.now()}. Plan: `md_guides/experiments/experiment_v2.md`. Setup in [Setup](#setup).",
         "", "## OP-EXP 4: fine-tune peak lr (from 1.1 @ 20000, 6k its, 10% warmup + cosine)", "",
         f"| Arm | peak lr | warmup | exp | status | jobs | best ckpt (val loss) | {METRIC_HDR} |",
         "|---" * 15 + "|",
         f"| 1.3 / 1.5 (ref) | 1e-4 | 5% | `{REF_FT}` | tested | — | "
         f"{f'{ref_best[0]} ({E.fmt(ref_best[1])})' if ref_best else REF_CKPT} | {score_cells(ref)} |"]
    per_volume = [("1.5 (ref, rm200)", REF_FT, REF_CKPT, ref_path)] if ref_path else []
    for key, arm in state["op4"].items():
        ft, te = arm["ft"], arm["test"]
        s = fresh_scores(te)
        best = f"{ft['best_ckpt']} ({E.fmt(ft.get('best_val_loss'))})" if "best_ckpt" in ft else "—"
        status = te["status"] if arm["stage"] in ("test", "done") else ft["status"]
        jobs = ",".join(ft["jobs"] + te["jobs"]) or "—"
        L.append(f"| {key} | {E.lr_fmt(ft['lr'])} | {WARMUP_FRAC:.0%} | `{ft['exp']}` | {status} | {jobs} | "
                 f"{best} | {score_cells(s)} |")
        if te.get("summary_csv"):
            per_volume.append((key, ft["exp"], te.get("ckpt"), te["summary_csv"]))
    L += ["", f"## OP-EXP 5: remove_small_components (EXP 1.3 @ {REF_CKPT} labels, completely test)", "",
          f"| Arm | remove_small_components | exp | status | job | {METRIC_HDR} |",
          "|---" * 13 + "|",
          f"| 1.5 (ref) | 200 | `{REF_FT}` | tested | — | {score_cells(ref)} |"]
    for key, a in state["op5"].items():
        s = fresh_scores(a)
        L.append(f"| {key} | {a['rm']} | `{a['exp']}` | {a['status']} | {','.join(a['jobs']) or '—'} | "
                 f"{score_cells(s)} |")
        if a.get("summary_csv"):
            per_volume.append((f"{key} (rm{a['rm']})", a["exp"], REF_CKPT, a["summary_csv"]))
    L += ["", "Test metrics are the FISBe ones, mean over the 7 completely test volumes: **S** = 0.5·avF1 + "
          "0.5·C; **avF1** = F1 averaged over clDice thresholds 0.1–0.9; **C** = mean GT skeleton coverage; "
          "**clDiceTP** = mean clDice of true positives; **tp** = fraction of GT matched at clDice ≥ 0.5; "
          "**FS** / **FM** = false splits / merges per volume; **nPred / nGT** = instances per volume.", ""]
    if per_volume:
        L += ["## Per-volume test results", ""]
        for title, exp, ckpt, rel in per_volume:
            rows = E.score_rows(os.path.join(REPO, rel))
            L += [f"**{title}** (`{exp}` @ {ckpt}; `{rel}`)", "",
                  "| volume | S | avF1 | C | clDiceTP | tp | FS | FM | nPred | nGT |", "|---" * 10 + "|"]
            L += [f"| {r['sample']} | {E.fmt(r['S'])} | {E.fmt(r['avF1'])} | {E.fmt(r['C'])} | "
                  f"{E.fmt(r['clDiceTP'])} | {E.fmt(r['tp'])} | {E.fmt(r['FS'], 0)} | {E.fmt(r['FM'], 0)} | "
                  f"{E.fmt(r['num_pred'], 0)} | {E.fmt(r['num_gt'], 0)} |" for r in rows] + [""]
    try:
        L += setup_section(state)
    except Exception as e:  # never let the status page break a tick
        L += ["## Setup", "", f"(setup section failed: {type(e).__name__}: {e})", ""]
    L += ["## Event log", ""] + [f"- {e}" for e in state.get("events", [])] + [""]
    with open(STATUS_MD, "w") as fh:
        fh.write("\n".join(L))


def setup_section(state):
    ref_lane = {"pre": {"key": SRC_KEY}, "ft": {"key": REF_FT_KEY, "overlays": REF_FT_OVERLAYS}}
    ref_arm = {"exp": REF_FT, "src_ckpt": SRC_CKPT, "overlays": REF_FT_OVERLAYS}
    train_cols = [(f"1.3 (ref)", E.run_config(REF_FT), {"arm": ref_arm, "lane": ref_lane, "part": "ft"})]
    for key, arm in state["op4"].items():
        ft = arm["ft"]
        lane = {"pre": {"key": SRC_KEY}, "ft": ft}
        train_cols.append((f"{key}", E.run_config(ft["exp"]) if "src_ckpt" in ft else None,
                           {"arm": ft, "lane": lane, "part": "ft"}))
    L = ["## Setup", "",
         f"Preset `{E.PRESET}` + base `{E.BASE}`, account `{E.ACCOUNT}`, L40S (compile + fp16 raw + "
         "fast_affinities). Values are read from each run's merged `metrics/ppp/<exp>/config.toml`. "
         "OP-EXP 4 best checkpoint = lowest completely-val loss (`<exp>/train/val_metrics.csv`).", "",
         "### OP-EXP 4 training", ""] + E.setup_tables(train_cols, E.TRAIN_FIELDS)
    test_cols = []
    for key, arm in state["op4"].items():
        te = arm["test"]
        if te["status"] in ("testing", "tested", "failed"):
            test_cols.append((f"{key} test", E.run_config(arm["ft"]["exp"]),
                              {"arm": te, "lane": {"ft": arm["ft"]}, "part": "test"}))
    for key, a in state["op5"].items():
        if a["status"] in ("evaluating", "tested", "failed"):
            test_cols.append((f"{key} eval", E.run_config(a["exp"]),
                              {"arm": {"ckpt": REF_CKPT}, "lane": ref_lane, "part": "test"}))
    if test_cols:
        L += ["### Test / evaluation", ""] + E.setup_tables(test_cols, E.TEST_FIELDS)
    return L


# ----------------------------------------------------------------------------- main

@contextlib.contextmanager
def locked_state():
    os.makedirs(STATE_DIR, exist_ok=True)
    with open(STATE + ".lock", "w") as lk:
        fcntl.flock(lk, fcntl.LOCK_EX)
        state = json.load(open(STATE)) if os.path.exists(STATE) else initial_state()
        try:
            yield state
        finally:
            if not DRY:
                tmp = STATE + ".tmp"
                with open(tmp, "w") as fh:
                    json.dump(state, fh, indent=1)
                os.replace(tmp, STATE)
                write_status(state)


def main():
    global DRY
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("cmd", choices=["tick", "status", "requeue-tests"])
    args = ap.parse_args()
    DRY = E.DRY = args.dry_run
    with locked_state() as state:
        if args.cmd == "requeue-tests":
            requeue_tests(state)
            tick(state)
        if args.cmd == "tick":
            tick(state)
        if DRY:
            print("\n".join(state["events"][-20:]))
    if os.path.exists(STATUS_MD) and args.cmd == "status":
        print(open(STATUS_MD).read())


if __name__ == "__main__":
    main()
