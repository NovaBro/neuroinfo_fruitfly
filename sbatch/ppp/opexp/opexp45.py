#!/usr/bin/env python3
"""experiment_v2 OP-EXP 4 + 5 driver (md_guides/experiments/experiment_v2.md).

OP-EXP 4 (fine-tune hyperparameters): fine-tune expv2-e1.1-pre-n1000 @ 20000 on completely for 6k its,
  WarmupCosine with 10% warmup, peak lr 5e-5 / 1e-5 / 5e-6 (arms 4.1-4.3); test each arm's
  lowest-val-loss checkpoint on all 7 completely test volumes (sparse pred_affs pipeline, eval_rm200).
  Reference: EXP 1.3 / 1.5 (same source checkpoint, peak lr 1e-4, 5% warmup).
OP-EXP 5 (eval threshold): re-evaluate EXP 1.3's existing test labels (expv2-e1.3-ft-n1000-completely
  @ 23000) with remove_small_components = 500 / 1000 / 1500 (arms 5.1-5.3). CPU only: each arm gets its
  own experiment dir holding a copy of 1.3's test/instanced/23000 tree, so 1.3's own rm200 results are
  never overwritten. Reference: EXP 1.5 (rm200).

Idempotent state machine; ``opexp45_tick.sh`` runs ``tick`` every ~10 min on a CPU node and resubmits
itself until everything is tested. Shares the SLURM / training / test / scoring / status-table helpers
of ``sbatch/ppp/expv2/expv2_e1.py`` (imported as E).

From the repo root:
  python3 sbatch/ppp/opexp/opexp45.py tick       # one step (safe by hand)
  python3 sbatch/ppp/opexp/opexp45.py status
  python3 sbatch/ppp/opexp/opexp45.py --dry-run tick

Decisions (user, 2026-11-09): account torch_pr_61_general; OP-EXP 4 tests the lowest completely-val-loss
checkpoint at remove_small_components 200 only; no extra arms.
"""
