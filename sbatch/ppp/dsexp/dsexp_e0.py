#!/usr/bin/env python3
"""experiment_v2 Dataset Experiments EXP 0 driver (md_guides/experiments/experiment_v2.md).

EXP 0.1: train baseline_v1_completely from scratch on completely (18 train vols), val on completely val (5 vols),
         35k its / 10 h (user 2026-11-09; plan said 100k), peak lr 4e-4, 10% warmup + cosine, FMAPs 15, ckpt + val
         every 5k; same model / L40S speed settings as EXP 1/2 (expv2_e1_common.toml + dsexp_pre.toml).
EXP 0.2: test the lowest-val-loss checkpoint on the 7 completely test volumes (sparse pred_affs pipeline) with
         remove_small_components 1500 (user; eval_rm1500.toml, best in OP-EXP 5).

Idempotent state machine; ``dsexp_e0_tick.sh`` runs ``tick`` every ~10 min on a CPU node until done. Uses the
train / select / test / score helpers of ``sbatch/ppp/expv2/expv2_e1.py`` (imported as E).

From the repo root:
  python3 sbatch/ppp/dsexp/dsexp_e0.py tick        # one step (safe by hand)
  python3 sbatch/ppp/dsexp/dsexp_e0.py status
  python3 sbatch/ppp/dsexp/dsexp_e0.py --dry-run tick
"""
from __future__ import annotations

import argparse
import contextlib
import fcntl
import json
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
sys.path.insert(0, os.path.join(REPO, "sbatch", "ppp", "expv2"))
import expv2_e1 as E  # noqa: E402

# 2026-11-10 (user): submit on torch_pr_61_tandon_priority (fair-share 0.32 vs 0.11 on general; GPU jobs were stuck
# behind ~420 higher-priority l40s_public jobs). Applies to every E.submit_* call made by this driver.
ACCOUNT = "torch_pr_61_tandon_priority"
E.ACCOUNT = ACCOUNT

STATE_DIR = os.path.join(E.METRICS, "dsexp_e0")
STATE = os.path.join(STATE_DIR, "state.json")
STATUS_MD = os.path.join(REPO, "md_guides", "experiments", "dsexp_e0_status.md")

EXP = "baseline_v1_completely"
MAX_IT = 35000
TIME = "10:00:00"
# eval_rm1500.toml rides along as a training overlay too (its [evaluation] keys are unused by training);
# in the test stack it comes after the default eval_rm200.toml, so 1500 wins.
OVERLAYS = E.COMMON + ["dsexp_pre.toml", "dsexp_completely.toml", "dsexp_10h.toml", "eval_rm1500.toml"]

DRY = False


def initial_state():
    return {
        "train": {"key": "0.1", "exp": EXP, "status": "new", "jobs": [], "retries": 0, "max_it": MAX_IT,
                  "overlays": OVERLAYS, "label": "train completely from scratch (35k its / 10 h)"},
        "test": {"key": "0.2", "status": "wait", "jobs": [], "retries": 0,
                 "label": "test completely, best 0.1 ckpt, remove_small_components 1500"},
        "stage": "train", "events": [], "done": False,
    }


def tick(state):
    tr, te = state["train"], state["test"]
    if state["stage"] == "train":
        if tr["status"] == "new":
            E.submit_train(state, tr, TIME)
        elif tr["status"] == "training" and E.advance_training(state, tr, TIME):
            E.select_best(state, tr)
            state["stage"] = "test"
            E.submit_test(state, tr, te)
        if tr["status"] == "failed":
            state["stage"] = "failed"
    elif state["stage"] == "test":
        if te["status"] == "wait":
            E.submit_test(state, tr, te)
        elif te["status"] == "testing":
            E.advance_testing(state, tr, te)
        if te["status"] in ("tested", "failed"):
            state["stage"] = "done" if te["status"] == "tested" else "failed"
    if state["stage"] in ("done", "failed") and not state.get("done"):
        state["done"] = True
        E.log(state, f"EXP 0 driver finished ({state['stage']})")


def write_status(state):
    tr, te = state["train"], state["test"]
    s = {}
    if te.get("summary_csv") and os.path.exists(os.path.join(REPO, te["summary_csv"])):
        s = E.read_scores(os.path.join(REPO, te["summary_csv"]))
    best = f"{tr['best_ckpt']} ({E.fmt(tr.get('best_val_loss'))})" if "best_ckpt" in tr else "—"
    cells = (f"**{E.fmt(s['S'])}** | {E.fmt(s['avF1'])} | {E.fmt(s['C'])} | {E.fmt(s['clDiceTP'])} | "
             f"{E.fmt(s['tp'])} | {E.fmt(s['FS'], 2)} | {E.fmt(s['FM'], 2)} | "
             f"{E.fmt(s['num_pred'], 0)} / {E.fmt(s['num_gt'], 1)}") if s else " | ".join(["—"] * 8)
    L = ["# experiment_v2 Dataset Experiments EXP 0 status (auto-generated by `sbatch/ppp/dsexp/dsexp_e0.py`)", "",
         f"Last update: {E.now()}. Plan: `md_guides/experiments/experiment_v2.md`.", "",
         "| Step | What | exp | status | jobs | best ckpt (val loss) | S | avF1 | C | clDiceTP | tp | FS | FM | nPred / nGT |",
         "|---" * 14 + "|",
         f"| 0.1 | {tr['label']} | `{EXP}` | {tr['status']} | {','.join(tr['jobs']) or '—'} | {best} | "
         + " | ".join(["—"] * 8) + " |",
         f"| 0.2 | {te['label']} | `{EXP}` | {te['status']} | {','.join(te['jobs']) or '—'} | "
         f"{te.get('ckpt', '—')} | {cells} |", "",
         f"Setup: preset `{E.PRESET}` + base `{E.BASE}` + {', '.join(f'`{o}`' for o in OVERLAYS)}; "
         f"account `{E.ACCOUNT}`; best checkpoint = lowest completely-val loss (`<exp>/train/val_metrics.csv`). "
         "Test metrics are the FISBe ones (S = 0.5·avF1 + 0.5·C), mean over the 7 completely test volumes.", "",
         "## Event log", ""] + [f"- {e}" for e in state["events"]] + [""]
    with open(STATUS_MD, "w") as fh:
        fh.write("\n".join(L))


@contextlib.contextmanager
def locked_state():
    os.makedirs(STATE_DIR, exist_ok=True)
    with open(STATE + ".lock", "w") as lk:
        fcntl.flock(lk, fcntl.LOCK_EX)
        state = json.load(open(STATE)) if os.path.exists(STATE) else initial_state()
        try:
            yield state
        finally:
            if not DRY:
                tmp = STATE + ".tmp"
                with open(tmp, "w") as fh:
                    json.dump(state, fh, indent=1)
                os.replace(tmp, STATE)
                write_status(state)


def main():
    global DRY
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("cmd", choices=["tick", "status", "requeue-test"])
    args = ap.parse_args()
    DRY = E.DRY = args.dry_run
    with locked_state() as state:
        te = state["test"]
        if args.cmd == "requeue-test" and state["stage"] == "test" and te["status"] == "testing":
            if not DRY:
                import subprocess
                subprocess.run(["scancel"] + te["jobs"])
            te.setdefault("requeued_jobs", []).extend(te["jobs"])
            te["jobs"], te["status"], te["retries"] = [], "wait", 0
            E.log(state, f"EXP 0.2: cancelled test chain {','.join(te['requeued_jobs'])} to requeue on {ACCOUNT}")
            tick(state)
        if args.cmd == "tick":
            tick(state)
        if DRY:
            print("\n".join(state["events"][-10:]))
    if args.cmd == "status" and os.path.exists(STATUS_MD):
        print(open(STATUS_MD).read())


if __name__ == "__main__":
    main()
