#!/bin/bash
# experiment_v1 EXP 3: fine-tune a pretrained noenc checkpoint on fisbe/completely.
#
# Seeds a new experiment dir with the source checkpoint (model + Adam state), so
# train.py's get_latest_checkpoint resumes from it at iteration CKPT and trains to
# CKPT + FT_ITERS (default 50000). Checkpoints every 2000 continue the source's
# numbering (e.g. 40000 → 42000 … 90000). Same H200 settings as EXP 2.
#
# From repo root:
#   ./sbatch/ppp/exp_v1_finetune.sh [--dry-run] <preset> <src_exp_id> <ckpt> [extra ppp_submit_train.sh flags…]
#   ./sbatch/ppp/exp_v1_finetune.sh our-noenc-c1k_v1_u8 our-noenc-c1k_v1_u8 40000
#
# New exp id: exp3-<src_exp_id without "our-">-ft<ckpt>-completely

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
cd "${REPO_ROOT}"

DRY=()
if [[ "${1:-}" == "--dry-run" ]]; then DRY=(--dry-run); shift; fi
if (( $# < 3 )); then sed -n '2,13p' "$0" >&2; exit 1; fi
PRESET="$1"; SRC="$2"; CKPT="$3"; shift 3
FT_ITERS="${FT_ITERS:-50000}"

SETUP="PatchPerPix/experiments/flylight/setups/setup01/configs/exp"
SRC_CKPT="metrics/ppp/${SRC}/train/train_net_checkpoint_${CKPT}"
EXP_ID="exp3-${SRC#our-}-ft${CKPT}-completely"
DST_DIR="metrics/ppp/${EXP_ID}/train"
OVERLAY="exp3_ft_${SRC#our-}_${CKPT}.toml"
MAX_IT=$((CKPT + FT_ITERS))

[[ -f "${SRC_CKPT}" ]] || { echo "Error: missing ${SRC_CKPT}" >&2; exit 1; }

cat > "${SETUP}/${OVERLAY}" <<EOF
# experiment_v1 EXP 3 (generated by sbatch/ppp/exp_v1_finetune.sh): fine-tune
# ${SRC} @ ${CKPT} on fisbe/completely for ${FT_ITERS} iterations (to ${MAX_IT}).
# Stack after the preset overlay and exp_v1_h200.toml.
[data]
train_datasets = ["completely"]

[training]
max_iterations = ${MAX_IT}
EOF
echo "wrote ${SETUP}/${OVERLAY}"

if [[ ${#DRY[@]} -eq 0 ]]; then
  mkdir -p "${DST_DIR}"
  existing="$(ls "${DST_DIR}" | grep -c '^train_net_checkpoint_' || true)"
  if [[ "${existing}" -eq 0 ]]; then
    cp -v "${SRC_CKPT}" "${DST_DIR}/"
  else
    echo "${DST_DIR} already has ${existing} checkpoint(s); resuming, not re-seeding"
  fi
fi

"${SCRIPT_DIR}/ppp_submit_train.sh" "${DRY[@]+"${DRY[@]}"}" "${PRESET}" \
  --base original_default.toml --id "${EXP_ID}" \
  --config exp_v1_h200.toml --config "${OVERLAY}" \
  --partition h200_public --cpus 16 --account torch_pr_61_tandon_advanced \
  --time 14:00:00 "$@"
